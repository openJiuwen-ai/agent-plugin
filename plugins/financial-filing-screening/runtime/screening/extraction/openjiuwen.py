class ExtractionConfigurationError(ValueError):
    """Raised when required model configuration is absent or invalid."""


@dataclass(frozen=True, slots=True)
class OpenJiuwenExtractionConfig:
    provider: str
    model_name: str
    api_base: str
    api_key: str
    verify_ssl: bool = True
    max_tokens: int = 1_024
    max_retries: int = 1
    reasoning_effort: str | None = None
    enable_thinking: bool | None = None

    def request_options(self) -> dict[str, Any]:
        options = {"reasoning_effort": self.reasoning_effort} if self.reasoning_effort else {}
        if self.enable_thinking is not None:
            options["extra_body"] = {
                "chat_template_kwargs": {"enable_thinking": self.enable_thinking}
            }
        return options


def _parse_bool(name: str, value: str) -> bool:
    normalized = value.strip().casefold()
    if normalized in {"1", "true", "yes", "on"}:
        return True
    if normalized in {"0", "false", "no", "off"}:
        return False
    raise ExtractionConfigurationError(
        f"{name} must be one of true/false, yes/no, on/off, or 1/0; got {value!r}."
    )


def load_extraction_config(
    environ: Mapping[str, str] | None = None,
) -> OpenJiuwenExtractionConfig:
    """Load OpenRouter or explicitly selected local Ollama via the SDK OpenAI client.

    Local selection never reuses a cloud credential or silently falls back to it.
    Network containment during evaluation is enforced by the comparison runner.
    """

    env = os.environ if environ is None else environ
    local = env.get("OPENJIUWEN_MODEL_PROVIDER", "").strip().casefold() == "ollama"
    required = REQUIRED_ENV_VARS[:-1] if local else REQUIRED_ENV_VARS
    missing = [name for name in required if not env.get(name, "").strip()]
    if missing:
        raise ExtractionConfigurationError(
            "Missing required API configuration: "
            + ", ".join(missing)
            + ". Copy .env.example to .env and set OPENJIUWEN_API_KEY."
        )

    provider = env["OPENJIUWEN_MODEL_PROVIDER"].strip()
    if not local and provider.casefold() != CANONICAL_PROVIDER.casefold():
        raise ExtractionConfigurationError(
            "OPENJIUWEN_MODEL_PROVIDER must be 'OpenRouter' or 'Ollama' for this "
            f"configuration; got {provider!r}."
        )

    api_base = env["OPENJIUWEN_API_BASE"].strip()
    if local:
        endpoint = urlsplit(api_base)
        if (endpoint.scheme != "http" or endpoint.hostname != "127.0.0.1"
                or endpoint.port != 11434 or endpoint.path.rstrip("/") != "/v1"
                or endpoint.username or endpoint.password or endpoint.query or endpoint.fragment):
            raise ExtractionConfigurationError("Ollama requires http://127.0.0.1:11434/v1 for this local integration.")

    raw_max_tokens = env.get("OPENJIUWEN_EXTRACTION_MAX_TOKENS", "2048").strip()
    try:
        max_tokens = int(raw_max_tokens)
    except ValueError as exc:
        raise ExtractionConfigurationError(
            "OPENJIUWEN_EXTRACTION_MAX_TOKENS must be a positive integer; "
            f"got {raw_max_tokens!r}."
        ) from exc
    if max_tokens <= 0:
        raise ExtractionConfigurationError(
            "OPENJIUWEN_EXTRACTION_MAX_TOKENS must be greater than zero."
        )

    return OpenJiuwenExtractionConfig(
        provider="OpenAI" if local else CANONICAL_PROVIDER,
        model_name=env["OPENJIUWEN_MODEL_NAME"].strip(),
        api_base=api_base,
        api_key="ollama-local" if local else env["OPENJIUWEN_API_KEY"].strip(),
        verify_ssl=_parse_bool(
            "OPENJIUWEN_VERIFY_SSL", env.get("OPENJIUWEN_VERIFY_SSL", "true")
        ),
        max_tokens=max_tokens,
        max_retries=0 if local else 1,
        # Keep the vendor-specific template choice separate from reasoning_effort.
        reasoning_effort=None,
        # Bound structured extraction latency independently of the host chat's
        # server default. The metric definition below disambiguates operating cash
        # flow without a reasoning trace. Keep Qwen options local and model-scoped.
        enable_thinking=False if local and env["OPENJIUWEN_MODEL_NAME"].strip().casefold()
        in {"qwen3-14b", "qwen/qwen3-14b"} else None,
    )


def extraction_response_schema() -> dict[str, Any]:
    """JSON Schema shared by native structured output and LLMComponent validation."""

    nullable_string = {"anyOf": [{"type": "string", "minLength": 1}, {"type": "null"}]}
    return {
        "type": "object",
        "properties": {
            "status": {
                "type": "string",
                "enum": [status.value for status in ExtractionStatus],
            },
            "metric_name": {
                "type": "string",
                "enum": [metric.value for metric in MetricName],
            },
            "fiscal_year": {"type": "integer", "minimum": 1900, "maximum": 9999},
            "value": {"anyOf": [{"type": "number"}, {"type": "null"}]},
            "unit": {
                "anyOf": [
                    {"type": "string", "enum": [unit.value for unit in MetricUnit]},
                    {"type": "null"},
                ]
            },
            "exact_row_label": nullable_string,
            "source_filename": nullable_string,
            "pdf_page_index": {
                "anyOf": [{"type": "integer", "minimum": 0}, {"type": "null"}]
            },
            "printed_document_page": nullable_string,
            "section_or_statement_name": nullable_string,
            "lines": {
                "anyOf": [
                    {
                        "type": "array",
                        "items": {"type": "string", "pattern": "^L[1-9][0-9]*$"},
                        "minItems": 1,
                        "maxItems": 3,
                    },
                    {"type": "null"},
                ]
            },
            "error_message": nullable_string,
        },
        "required": [
            "status",
            "metric_name",
            "fiscal_year",
            "value",
            "unit",
            "exact_row_label",
            "source_filename",
            "pdf_page_index",
            "printed_document_page",
            "section_or_statement_name",
            "lines",
            "error_message",
        ],
        "additionalProperties": False,
    }


def create_metric_extraction_component(config: OpenJiuwenExtractionConfig) -> Any:
    """Create the reusable LLMComponent used for one evidence-bound metric."""

    from openjiuwen.core.foundation.llm import (
        ModelClientConfig,
        ModelRequestConfig,
        SystemMessage,
        UserMessage,
    )
    from openjiuwen.core.workflow import LLMCompConfig, LLMComponent

    response_schema = extraction_response_schema()
    return LLMComponent(
        LLMCompConfig(
            model_client_config=ModelClientConfig(
                client_provider=config.provider,
                api_key=config.api_key,
                api_base=config.api_base,
                verify_ssl=config.verify_ssl,
                max_retries=config.max_retries,
            ),
            model_config=ModelRequestConfig(
                model=config.model_name,
                max_tokens=config.max_tokens,
                # openJiuwen samples (temperature 0.95 / top_p 0.1), so the same filing could
                # pass in one run and fail in the next (Caterpillar FY2024 did). A fixed seed
                # makes each request repeatable. (Runaway whitespace output seen while
                # testing temperature 0 was caused by removing openJiuwen's JSON instruction,
                # not by greedy decoding; the default sampling is kept only so that one
                # thing changes at a time.)
                seed=0,
                **config.request_options(),
                response_format={
                    "type": "json_schema",
                    "json_schema": {
                        "name": "financial_metric_extraction",
                        "strict": True,
                        "schema": response_schema,
                    },
                },
            ),
            system_prompt_template=SystemMessage(
                content=(
                    "You extract exactly one reported financial metric from the supplied "
                    "EVIDENCE_CHUNKS. Use no outside knowledge. Do not calculate ratios, "
                    "totals, sums, differences, growth, margins, or policy decisions. "
                    "Every line of chunk_text starts with its line ID on that page, for "
                    "example 'L41'. Cite your evidence by line ID only: put in `lines` the "
                    "ID of the one row that holds the value and its label. Add the next "
                    "line (at most 3 lines in all) only when that row is wrapped onto it. "
                    "Do not cite titles, column headers or date rows (the system reads the "
                    "page header for the fiscal year and unit itself), and never cite two "
                    "different rows. Do not copy the text of the lines; the system reads "
                    "them itself. Copy the exact row label (without its line ID) and the "
                    "provenance fields. "
                    "Return the value exactly as printed in that row, never rescaled. The "
                    "unit is the scale the statement header states for dollar amounts: "
                    "'$ in Millions' means USD_MILLIONS, '$ in Thousands' means "
                    "USD_THOUSANDS, and a header with no dollar scale (for example 'USD ($)' "
                    "alone, or one that scales only shares) means USD, with the full "
                    "printed number as the value. "
                    "A PDF page index and printed document page are "
                    "different fields: copy each independently and leave the printed page "
                    "null when the chunk says it is null. Return VERIFIED only when the "
                    "requested fiscal year, value, unit, row, and provenance are explicit. "
                    "If the year-to-column mapping is ambiguous or the evidence does not "
                    "directly support the value, return UNVERIFIED with value null and a "
                    "specific error_message. Never guess. "
                    "Operating cash flow means the reported net cash provided by or used "
                    "in operating activities on the cash flow statement; select that total, "
                    "not profit or an individual adjustment. Match the requested metric by "
                    "meaning rather than by exact row-label spelling."
                )
            ),
            user_prompt_template=UserMessage(
                content=(
                    "REQUEST:\n{{request_json}}\n\n"
                    "EVIDENCE_CHUNKS (the only allowed source):\n{{evidence_json}}"
                )
            ),
            # openJiuwen's default JSON instruction is kept deliberately: it is the only
            # place the model sees the schema. Without it Qwen3-14B does not know that
            # `error_message` is required even when null, and pads with whitespace until the
            # token budget runs out (Hershey FY2019, 3M FY2022: finish_reason=length).
            response_format={"type": "json"},
            output_config=response_schema,
            enable_history=False,
        )
    )


def build_extraction_workflow(config: OpenJiuwenExtractionConfig) -> Any:
    """Build the current SDK's Start -> LLMComponent -> End workflow."""

    from openjiuwen.core.workflow import (
        End,
        Start,
        Workflow,
        WorkflowCard,
    )

    response_schema = extraction_response_schema()
    workflow = Workflow(
        card=WorkflowCard(
            id="financial_metric_extraction",
            name="Financial Metric Extraction",
            version="1.0.0",
            description="Extracts one reported financial metric from retrieved evidence.",
            input_params={
                "type": "object",
                "properties": {
                    "request_json": {"type": "string"},
                    "evidence_json": {"type": "string"},
                },
                "required": ["request_json", "evidence_json"],
                "additionalProperties": False,
            },
        )
    )
    llm = create_metric_extraction_component(config)

    workflow.set_start_comp(
        "start",
        Start(),
        inputs_schema={
            "request_json": "${request_json}",
            "evidence_json": "${evidence_json}",
        },
    )
    workflow.add_workflow_comp(
        "llm",
        llm,
        inputs_schema={
            "request_json": "${start.request_json}",
            "evidence_json": "${start.evidence_json}",
        },
    )
    workflow.set_end_comp(
        "end",
        End(),
        inputs_schema={key: f"${{llm.{key}}}" for key in response_schema["required"]},
    )
    workflow.add_connection("start", "llm")
    workflow.add_connection("llm", "end")
    return workflow


def _normalize_text(value: str) -> str:
    return " ".join(value.split())


# Kept under its old name for callers elsewhere in the package.
_numbers_in_text = numbers_in_text


def _unsupported_result(
    request: MetricExtractionRequest,
    message: str,
    candidate: MetricExtractionResult | None = None,
) -> MetricExtractionResult:
    candidate_data = candidate.model_dump() if candidate is not None else {}
    candidate_data.update(
        status=ExtractionStatus.UNVERIFIED,
        metric_name=request.metric_name,
        fiscal_year=request.fiscal_year,
        value=None,
        error_message=message,
    )
    for field in (
        "unit",
        "exact_row_label",
        "source_filename",
        "pdf_page_index",
        "printed_document_page",
        "section_or_statement_name",
        "lines",
        "evidence_text",
    ):
        candidate_data.setdefault(field, None)
    return MetricExtractionResult.model_validate(candidate_data)


def _error_result(request: MetricExtractionRequest, message: str) -> MetricExtractionResult:
    return MetricExtractionResult(
        status=ExtractionStatus.ERROR,
        metric_name=request.metric_name,
        fiscal_year=request.fiscal_year,
        value=None,
        unit=None,
        exact_row_label=None,
        source_filename=None,
        pdf_page_index=None,
        printed_document_page=None,
        section_or_statement_name=None,
        lines=None,
        error_message=message,
    )


# "$ in Millions", "(in millions, except per share amounts)", "In USD thousands" — but not
# "shares in Millions", which scales share counts only. SEC renders 3M's FY2022 income
# statement as "USD ($) shares in Millions" with dollars printed in full; reading that
# header as a dollar scale rejected the correct unscaled answer.
_DOLLAR_SCALE = re.compile(r"(?<!shares )\bin\s+(?:usd\s+)?(millions|thousands)\b")


def _dollar_scales(page_text: str) -> set[str]:
    return {m.group(1) for m in _DOLLAR_SCALE.finditer(page_text.casefold())}


def validate_extraction_support(
    candidate: MetricExtractionResult,
    request: MetricExtractionRequest,
    evidence: tuple[Evidence, ...],
    document: ParsedPdf,
) -> MetricExtractionResult:
    """Reject a structured answer that is not grounded in retrieved chunks.

    A VERIFIED answer that survives comes back with `evidence_text` filled from the
    cited page lines; the model never supplies that text.
    """

    if candidate.metric_name is not request.metric_name:
        return _unsupported_result(request, "Model returned a different metric name.", candidate)
    if candidate.fiscal_year != request.fiscal_year:
        return _unsupported_result(request, "Model returned a different fiscal year.", candidate)
    if candidate.status is not ExtractionStatus.VERIFIED:
        return candidate

    matching_evidence = tuple(
        item
        for item in evidence
        if item.source_filename == candidate.source_filename
        and item.pdf_page_index == candidate.pdf_page_index
        and item.printed_document_page == candidate.printed_document_page
        and item.section_or_statement_name == candidate.section_or_statement_name
    )
    if not matching_evidence or not any(item.chunk_text for item in matching_evidence):
        return _unsupported_result(
            request,
            "Returned provenance does not match a retrieved evidence chunk.",
            candidate,
        )

    # One definition of "this is the balance sheet", shared with retrieval routing. A
    # substring test for "balance sheet" rejected every filer who heads the statement
    # "Consolidated Financial Position" — a correct citation, refused on wording.
    from screening.retrieval.local import classify_statement_heading

    section = candidate.section_or_statement_name
    is_balance_sheet = section is not None and (
        "balance sheet" in section.casefold()
        or classify_statement_heading(section) == "Consolidated Balance Sheets"
    )
    if (
        request.metric_name in _BALANCE_SHEET_METRICS
        and section is not None
        and not is_balance_sheet
    ):
        return _unsupported_result(
            request,
            "Balance-sheet components must be cited from a balance-sheet statement.",
            candidate,
        )

    # The model cites line IDs; the page decides what they say. One shared check
    # (screening.citations) serves this step and final provenance validation alike.
    if (candidate.source_filename != document.source_filename
            or candidate.pdf_page_index is None
            or candidate.pdf_page_index >= document.page_count):
        return _unsupported_result(
            request, "Cited page does not exist in the ingested filing.", candidate)
    assert candidate.lines is not None and candidate.value is not None
    try:
        citation = resolve_line_citation(
            document.pages[candidate.pdf_page_index].raw_text,
            parse_line_ids(candidate.lines),
            row_label=candidate.exact_row_label,
            value=candidate.value,
        )
    except CitationError as exc:
        return _unsupported_result(request, str(exc), candidate)
    candidate = candidate.model_copy(update={"evidence_text": citation.text})

    page_text = "\n".join(
        item.chunk_text or ""
        for item in evidence
        if item.source_filename == candidate.source_filename
        and item.pdf_page_index == candidate.pdf_page_index
    )
    if not re.search(rf"(?<!\d){request.fiscal_year}(?!\d)", page_text):
        return _unsupported_result(
            request,
            "The requested fiscal year is not present in retrieved evidence from the cited page.",
            candidate,
        )

    scales = _dollar_scales(page_text)
    assert candidate.unit is not None
    if candidate.unit is MetricUnit.USD_MILLIONS and "millions" not in scales:
        return _unsupported_result(
            request,
            "USD_MILLIONS is not stated in retrieved evidence from the cited page.",
            candidate,
        )
    if candidate.unit is MetricUnit.USD_THOUSANDS and "thousands" not in scales:
        return _unsupported_result(
            request,
            "USD_THOUSANDS is not stated in retrieved evidence from the cited page.",
            candidate,
        )
    if candidate.unit is MetricUnit.USD and scales:
        return _unsupported_result(
            request,
            "Unscaled USD conflicts with the scale stated on the cited page.",
            candidate,
        )
    return candidate


def serialize_evidence(evidence: tuple[Evidence, ...], *, numbered: bool = False) -> str:
    """Evidence as the model sees it. `numbered` prefixes each line with its page line
    ID ("L41  ...") so that it can be cited; the risk path still quotes text and does
    not use it."""

    def text_of(item: Evidence) -> str | None:
        if numbered and item.chunk_text is not None and item.line_numbers is not None:
            return number_lines(item.chunk_text, item.line_numbers)
        return item.chunk_text

    payload = [
        {
            "source_filename": item.source_filename,
            "pdf_page_index": item.pdf_page_index,
            "printed_document_page": item.printed_document_page,
            "section_or_statement_name": item.section_or_statement_name,
            "chunk_text": text_of(item),
        }
        for item in evidence
    ]
    return json.dumps(payload, ensure_ascii=False, separators=(",", ":"))


# Which primary statement each metric is reported on. This is known from the domain, not
# something a term-frequency search should have to rediscover: total liabilities is on the
# balance sheet. Supplying it as a retrieval prior raised recall on real filings from
# 86.8% to 95.6%. It is a prior rather than a filter — see StatementRoutedRetriever.
METRIC_SECTIONS: dict[MetricName, tuple[str, ...]] = {
    MetricName.REVENUE: ("Consolidated Statements of Operations",),
    MetricName.OPERATING_INCOME: ("Consolidated Statements of Operations",),
    MetricName.OPERATING_CASH_FLOW: ("Consolidated Statements of Cash Flows",),
    MetricName.ASSETS: ("Consolidated Balance Sheets",),
    MetricName.LIABILITIES: ("Consolidated Balance Sheets",),
    MetricName.SHAREHOLDERS_EQUITY: ("Consolidated Balance Sheets",),
    MetricName.REDEEMABLE_NONCONTROLLING_INTERESTS: ("Consolidated Balance Sheets",),
    MetricName.NONCONTROLLING_INTERESTS: ("Consolidated Balance Sheets",),
    MetricName.OTHER_TEMPORARY_MEZZANINE_EQUITY: ("Consolidated Balance Sheets",),
}


def retrieve_metric_evidence(
    retriever: LocalBM25Retriever,
    metric_name: MetricName,
    *,
    top_k: int,
) -> tuple[Evidence, ...]:
    """Retrieve metric hits plus same-page scale context needed to verify units.

    A retriever that understands statement sections is given the metric's expected
    statement; a plain one is queried exactly as before, so PDF ingestion is unaffected.
    """

    query = METRIC_QUERIES[metric_name]
    sections = METRIC_SECTIONS.get(metric_name)
    if sections is not None and hasattr(retriever, "section_counts"):
        evidence = list(retriever.retrieve(query, sections=sections, top_k=top_k))
    else:
        evidence = list(retriever.retrieve(query, top_k=top_k))
    cited_pages = {item.pdf_page_index for item in evidence}
    seen = {
        (item.pdf_page_index, item.section_or_statement_name, item.chunk_text)
        for item in evidence
    }
    for chunk in retriever.chunks:
        key = (chunk.pdf_page_index, chunk.section, chunk.text)
        if (
            chunk.pdf_page_index in cited_pages
            and re.search(
                r"\bin\s+(?:usd\s+)?(?:millions|thousands)\b",
                chunk.text,
                re.IGNORECASE,
            )
            and key not in seen
        ):
            evidence.append(chunk.as_evidence())
            seen.add(key)
    return tuple(evidence)


def metric_result_from_payload(payload: Any) -> MetricExtractionResult:
    """Validate a component payload, restoring nullable fields dropped by End/state."""

    if isinstance(payload, dict):
        # The current End component intentionally removes dictionary entries
        # whose value is None. LLMComponent has already validated the complete
        # required JSON object, so restore only the schema's nullable fields.
        payload = dict(payload)
        for field in (
            "value",
            "unit",
            "exact_row_label",
            "source_filename",
            "pdf_page_index",
            "printed_document_page",
            "section_or_statement_name",
            "lines",
            "error_message",
        ):
            payload.setdefault(field, None)
    try:
        return MetricExtractionResult.model_validate(payload)
    except ValidationError as exc:
        raise RuntimeError(
            "openJiuwen returned invalid extraction JSON: "
            f"{exc.errors(include_url=False)}"
        ) from exc


def _validate_workflow_output(output: Any) -> MetricExtractionResult:
    from openjiuwen.core.workflow import WorkflowExecutionState, WorkflowOutput

    if not isinstance(output, WorkflowOutput):
        raise RuntimeError(
            f"openJiuwen returned {type(output).__name__}; expected WorkflowOutput."
        )
    if output.state is not WorkflowExecutionState.COMPLETED:
        raise RuntimeError(f"openJiuwen workflow did not complete: {output.state.value}.")

    payload = output.result
    if isinstance(payload, dict) and set(payload) == {"output"}:
        payload = payload["output"]
    return metric_result_from_payload(payload)


class OpenJiuwenFinancialExtractor:
    """Retrieve locally, then ask one LLMComponent to extract one fact at a time."""

    def __init__(
        self,
        config: OpenJiuwenExtractionConfig,
        *,
        top_k: int = 6,
    ) -> None:
        if top_k <= 0:
            raise ValueError("top_k must be greater than zero")
        self.config = config
        self.top_k = top_k
        self.workflow = build_extraction_workflow(config)

    async def extract(
        self,
        document: ParsedPdf,
        requests: Iterable[MetricExtractionRequest],
    ) -> tuple[MetricExtractionResult, ...]:
        """Return one validated result per request without sending the full filing."""

        from openjiuwen.core.runner import Runner

        requested = tuple(requests)
        if not requested:
            return ()

        retriever = LocalBM25Retriever.from_document(document)
        selected = tuple(
            (
                request,
                retrieve_metric_evidence(
                    retriever,
                    request.metric_name,
                    top_k=self.top_k,
                ),
            )
            for request in requested
        )
        results: list[MetricExtractionResult] = []
        runner_started = False
        try:
            runner_started = await Runner.start()
            if not runner_started:
                raise RuntimeError("openJiuwen Runner.start() reported failure.")

            for request, evidence in selected:
                if not evidence:
                    results.append(
                        _unsupported_result(request, "No local evidence matched this metric.")
                    )
                    continue
                try:
                    workflow_output = await Runner.run_workflow(
                        self.workflow,
                        {
                            "request_json": request.model_dump_json(),
                            "evidence_json": serialize_evidence(evidence, numbered=True),
                        },
                    )
                    candidate = _validate_workflow_output(workflow_output)
                    results.append(
                        validate_extraction_support(candidate, request, evidence, document))
                except Exception as exc:
                    results.append(
                        _error_result(
                            request,
                            f"openJiuwen extraction failed: {type(exc).__name__}: {exc}",
                        )
                    )
        except Exception as exc:
            message = f"openJiuwen runner failed: {type(exc).__name__}: {exc}"
            return tuple(_error_result(request, message) for request in requested)
        finally:
            if runner_started:
                await Runner.stop()
        return tuple(results)
