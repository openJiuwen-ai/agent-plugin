def filing_fixture(tmp_path, revenue=100, omit_income=False):
    directory = tmp_path / "filing"
    directory.mkdir()
    tables = [
        ("Document and Entity Information", [["Entity Registrant Name", "EXAMPLE INC"],
          ["Document Fiscal Year Focus", "2025"]]),
        ("Consolidated Statements of Operations", [
          ["Consolidated Statements of Operations - USD ($) $ in Millions", "12 Months Ended"],
          ["Dec. 31, 2025", "Dec. 31, 2024"], ["Total net sales", revenue, 90]]
          + ([] if omit_income else [["Operating income", 20, 18]])),
        ("Consolidated Balance Sheets", [
          ["Consolidated Balance Sheets - USD ($) $ in Millions"],
          ["Dec. 31, 2025", "Dec. 31, 2024"], ["Total assets", 200, 180],
          ["Total liabilities", 100, 90], ["Total shareholders' equity", 100, 90]]),
        ("Consolidated Statements of Cash Flows", [
          ["Consolidated Statements of Cash Flows - USD ($) $ in Millions"],
          ["Dec. 31, 2025", "Dec. 31, 2024"], ["Cash generated by operating activities", 15, 10]]),
    ]
    summary = []
    for i, (title, rows) in enumerate(tables, 1):
        filename = f"R{i}.htm"
        summary.append(f"<Report><ShortName>{title}</ShortName><HtmlFileName>{filename}</HtmlFileName></Report>")
        (directory / filename).write_text("<table>" + "".join(
            "<tr>" + "".join(f"<td>{cell}</td>" for cell in row) + "</tr>" for row in rows) + "</table>")
    (directory / "FilingSummary.xml").write_text("<FilingSummary>" + "".join(summary) + "</FilingSummary>")
    return directory


def test_tool_inspects_via_real_isolated_worker(tmp_path, monkeypatch):
    filing = filing_fixture(tmp_path)
    monkeypatch.setenv("FINANCIAL_SCREENING_PYTHON", sys.executable)
    out = tmp_path / "inspection"
    result = asyncio.run(tool_class().invoke({"mode": "inspect", "filing_dir": str(filing), "output_dir": str(out)}))
    assert result["success"] is True, result
    assert result["company_name"] == "EXAMPLE INC"
    assert result["fiscal_year"] == 2025
    assert len(result["reports"]) == 4
    assert result["model_calls"] == 0 and result["decision"] is None
    assert (out / "result.json").is_file()
    assert not (out / "report.json").exists()
    again = asyncio.run(tool_class().invoke({"mode": "inspect", "filing_dir": str(filing), "output_dir": str(out)}))
    assert again["success"] is False


