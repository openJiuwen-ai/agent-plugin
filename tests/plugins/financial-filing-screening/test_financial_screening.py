def test_html_risk_citations_do_not_inherit_cash_flow_heading(tmp_path, monkeypatch):
    filing = filing_fixture(tmp_path)
    summary = filing / "FilingSummary.xml"
    summary.write_text(summary.read_text().replace("</FilingSummary>",
        "<Report><ShortName>Risk disclosures</ShortName><HtmlFileName>R5.htm</HtmlFileName>"
        "</Report></FilingSummary>"))
    (filing / "R5.htm").write_text("<table><tr><td>Risk disclosures</td></tr>"
        "<tr><td>Regulatory litigation, legal tax customs disputes, supply chain risks, "
        "supplier concentration and manufacturing disruption are material risks.</td></tr></table>")
    checked = []

    def verify(evidence):
        note = [e for e in evidence if e["printed_document_page"] == "R5"]
        assert note
        assert all(e["section_or_statement_name"] == "Risk disclosures" for e in note)
        checked.append(True)

    install_fixture_model(monkeypatch, risk_evidence_check=verify)
    monkeypatch.setenv("FINANCIAL_SCREENING_MODEL", "offline-fixture")
    monkeypatch.setenv("FINANCIAL_SCREENING_ALLOW_INFERENCE", "1")
    out = tmp_path / "output"
    out.mkdir()
    result = asyncio.run(worker.run(SimpleNamespace(mode="screen", filing_dir=filing,
                                                    output_dir=out, timeout_seconds=30)))
    assert result["success"] is True
    assert len(checked) == 2


def test_partial_html_risk_clearance_cannot_produce_pass(tmp_path, monkeypatch):
    from screening.domain import RiskAssessment, RiskStatus
    from screening.workflows import screening as wf
    filing = filing_fixture(tmp_path)
    install_fixture_model(monkeypatch)

    def narrow_clearance(candidate, request, evidence):
        assessment = RiskAssessment(category=request.category, status=RiskStatus.CLEAR,
                                    rationale="A narrow passage says no material remediation cost.")
        return SimpleNamespace(to_risk_assessment=lambda: assessment)

    monkeypatch.setattr(wf, "validate_risk_support", narrow_clearance)
    monkeypatch.setenv("FINANCIAL_SCREENING_MODEL", "offline-fixture")
    monkeypatch.setenv("FINANCIAL_SCREENING_ALLOW_INFERENCE", "1")
    out = tmp_path / "output"
    out.mkdir()
    result = asyncio.run(worker.run(SimpleNamespace(mode="screen", filing_dir=filing,
                                                    output_dir=out, timeout_seconds=30)))
    report = json.loads((out / "report.json").read_text())
    assert all(c["status"] == "PASS" for c in report["criteria"])
    assert result["decision"] == "REVIEW"
    assert all(r["status"] == "UNVERIFIED" for r in report["risks"])
    assert all("narrow passage" in r["rationale"] for r in report["risks"])
