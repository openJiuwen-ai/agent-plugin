def install_fixture_model(monkeypatch, risk_evidence_check=None):
    from openjiuwen.core.workflow.components.llm.llm_comp import LLMExecutable
    from screening.workflows import screening as wf
    monkeypatch.setattr(wf, "_taxonomy_call", lambda config: lambda *args: {
        "income": "R2", "balance": "R3", "cashflow": "R4"})
    rows = {"revenue": "Total net sales", "operating_income": "Operating income",
            "operating_cash_flow": "Cash generated by operating activities",
            "assets": "Total assets", "liabilities": "Total liabilities",
            "shareholders_equity": "Total shareholders' equity"}
    provenance = ("source_filename", "pdf_page_index", "printed_document_page", "section_or_statement_name")

    class FixtureModel:
        async def invoke(self, *, messages):
            prompt = next(str(m.content) for m in messages if "REQUEST:\n" in str(m.content))
            decoder = json.JSONDecoder()
            request, _ = decoder.raw_decode(prompt.split("REQUEST:\n", 1)[1])
            evidence, _ = decoder.raw_decode(prompt.split("EVIDENCE_CHUNKS (the only allowed source):\n", 1)[1].lstrip())
            payload = {**request, "status": "UNVERIFIED", **dict.fromkeys(provenance),
                       "error_message": "Fixture has no supporting evidence."}
            if "metric_name" in request:
                payload.update(value=None, unit=None, exact_row_label=None, lines=None)
                row = rows.get(request["metric_name"])
                if row:
                    for item in evidence:
                        match = re.search(r"(?m)^(L\d+)\s+" + re.escape(row)
                                          + r"\s*\|\s*(\d+)\s*\|\s*(\d+)\s*$", item["chunk_text"] or "")
                        if match:
                            payload.update(status="VERIFIED", value=int(match.group(2 if request["fiscal_year"] == 2025 else 3)),
                                           unit="USD_MILLIONS", exact_row_label=row, lines=[match.group(1)], error_message=None)
                            payload.update({k: item[k] for k in provenance})
                            break
            else:
                if risk_evidence_check is not None:
                    risk_evidence_check(evidence)
                payload.update(rationale="No risk disclosure in the fictional fixture.", evidence_text=None)
            return SimpleNamespace(content=json.dumps(payload))

    async def factory(executable):
        return FixtureModel()
    monkeypatch.setattr(LLMExecutable, "_create_llm_instance", factory)


@pytest.mark.parametrize("revenue,expected", [(100, "REVIEW"), (80, "REJECT")])
def test_real_workflow_with_controlled_model_responses(tmp_path, monkeypatch, revenue, expected):
    filing = filing_fixture(tmp_path, revenue)
    install_fixture_model(monkeypatch)
    monkeypatch.setenv("FINANCIAL_SCREENING_MODEL", "offline-fixture")
    monkeypatch.setenv("FINANCIAL_SCREENING_ALLOW_INFERENCE", "1")
    out = tmp_path / "output"
    out.mkdir()
    result = asyncio.run(worker.run(SimpleNamespace(mode="screen", filing_dir=filing,
                                                    output_dir=out, timeout_seconds=30)))
    assert result["success"] is True and result["decision"] == expected
    report = json.loads((out / "report.json").read_text())
    assert report["decision"] == expected
    assert report["financials"]["revenue_current"]["value"] == str(revenue)
    assert report["financials"]["revenue_current"]["evidence"]
    assert len(report["criteria"]) == 5
    assert all(c["evidence"] for c in report["criteria"])
    assert all(r["status"] == "UNVERIFIED" for r in report["risks"])


