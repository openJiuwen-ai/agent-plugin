@pytest.mark.parametrize("provider,model,expected", [
    ("ollama", "Qwen3-14B", {"enable_thinking": False}),
    ("ollama", "Qwen/Qwen3-14B", {"enable_thinking": False}),
    ("ollama", "another-local-model", None),
    ("OpenRouter", "Qwen3-14B", None),
])
def test_qwen_template_survives_sdk_serialization_without_crossing_provider_boundary(
    monkeypatch, provider, model, expected,
):
    import httpx
    from openai import AsyncOpenAI
    from openjiuwen.core.foundation.llm.model_clients.openai_model_client import OpenAIModelClient
    from screening.extraction.openjiuwen import (
        create_metric_extraction_component, load_extraction_config,
    )
    config = load_extraction_config({
        "OPENJIUWEN_MODEL_PROVIDER": provider,
        "OPENJIUWEN_MODEL_NAME": model,
        "OPENJIUWEN_API_BASE": "http://127.0.0.1:11434/v1",
        "OPENJIUWEN_API_KEY": "fixture-cloud-key",
    })
    component = create_metric_extraction_component(config)
    captured = []

    def respond(request):
        captured.append(json.loads(request.content))
        return httpx.Response(200, json={
            "id": "fixture", "object": "chat.completion", "created": 0, "model": model,
            "choices": [{"index": 0, "finish_reason": "stop",
                         "message": {"role": "assistant", "content": "{}"}}],
        })

    async def send():
        async with AsyncOpenAI(api_key=component._config.model_client_config.api_key,
                               base_url="http://127.0.0.1:11434/v1",
                               http_client=httpx.AsyncClient(transport=httpx.MockTransport(respond))) as sdk:
            client = OpenAIModelClient(component._config.model_config,
                                       component._config.model_client_config)
            monkeypatch.setattr(client, "_create_async_openai_client", lambda **kwargs: sdk)
            await client.invoke(messages=[{"role": "user", "content": "fixture"}])

    asyncio.run(send())
    assert len(captured) == 1
    assert captured[0].get("chat_template_kwargs") == expected
    assert captured[0]["response_format"]["json_schema"]["strict"] is True
    if provider == "ollama":
        assert component._config.model_client_config.api_key != "fixture-cloud-key"


